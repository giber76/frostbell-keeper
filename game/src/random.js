// A tiny seeded RNG so a night can be replayed exactly: the same seed deals
// the same spawn order, the same upgrade cards and the same snow. Everything
// random in the game draws from one of these.

export function makeRng(seed) {
  let state = (seed >>> 0) || 1;
  return {
    next() {
      // mulberry32
      state = (state + 0x6d2b79f5) >>> 0;
      let t = state;
      t = Math.imul(t ^ (t >>> 15), t | 1);
      t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    },
    range(min, max) {
      return min + this.next() * (max - min);
    },
    int(min, max) {
      return Math.floor(this.range(min, max + 1));
    },
    pick(list) {
      return list[Math.floor(this.next() * list.length)];
    },
  };
}
